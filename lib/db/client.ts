import "server-only";

import { drizzle, type PostgresJsDatabase } from "drizzle-orm/postgres-js";
import postgres from "postgres";

import { config, databaseUrlForLog } from "@/lib/config";
import { logInfo } from "@/lib/logging";
import * as schema from "@/lib/db/schema";

/**
 * 连接不在整段 SSE 期间一直握着。
 * 流可能持续数秒；连接只在读取历史时打开，并在整轮成功结束后为了写入再打开。
 */

const globalForDatabase = globalThis as unknown as {
  advisorSql?: postgres.Sql;
  advisorSchemaReady?: Promise<void>;
};

function sqlClient(): postgres.Sql {
  if (!globalForDatabase.advisorSql) {
    logInfo("已创建数据库连接", {
      地址: databaseUrlForLog(config.databaseUrl),
    });
    globalForDatabase.advisorSql = postgres(config.databaseUrl, {
      max: 10,
      // 表已经存在时，CREATE TABLE IF NOT EXISTS 会发一条 NOTICE。不需要把它打进日志。
      onnotice: () => {},
    });
  }
  return globalForDatabase.advisorSql;
}

export function getDatabase(): PostgresJsDatabase<typeof schema> {
  return drizzle(sqlClient(), { schema });
}

export function getSqlClient(): postgres.Sql {
  return sqlClient();
}

export async function ensureConversationSchema(): Promise<void> {
  if (!globalForDatabase.advisorSchemaReady) {
    globalForDatabase.advisorSchemaReady = createConversationSchema().catch((error: unknown) => {
      globalForDatabase.advisorSchemaReady = undefined;
      throw error;
    });
  }
  await globalForDatabase.advisorSchemaReady;
}

async function createConversationSchema(): Promise<void> {
  const sql = sqlClient();
  await sql.unsafe(`
    CREATE TABLE IF NOT EXISTS conversation_messages (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      thread_id varchar(64) NOT NULL,
      role varchar(16) NOT NULL,
      content text NOT NULL,
      created_at timestamptz NOT NULL DEFAULT now()
    )
  `);
  await sql.unsafe(`
    CREATE INDEX IF NOT EXISTS ix_conversation_messages_thread_id_id
      ON conversation_messages (thread_id, id)
  `);
  logInfo("对话消息表已就绪");
}

export async function pingDatabase(): Promise<void> {
  await ensureConversationSchema();
  await sqlClient()`SELECT 1`;
}
